from __future__ import annotations

import hashlib
import json
from pathlib import Path
from typing import Any

from qsa_benchmark.benchmark.envelope import parse_envelope
from qsa_benchmark.benchmark.utils import canonical_json_bytes, sha256_file
from qsa_benchmark.protocol.config import load_protocol_config
from qsa_benchmark.protocol.experiment import canonical_csv_sha256

MANIFEST_PATH = "reference/deterministic_outputs/artifact_hashes.json"
INVENTORY_PATH = "reference/deterministic_outputs/artifact_inventory.json"
DIGEST_PATH = "reference/deterministic_outputs/protocol_digest.json"


_SOURCE_AUTHORITY_DIRECTORIES = (
    "src/qsa_benchmark",
    "configs/protocol",
    "configs/reference",
    "configs/verification",
    "registries",
    "scripts",
)
_SOURCE_AUTHORITY_FILES = (
    "pyproject.toml",
    "requirements.txt",
    "requirements-lock.txt",
    "reference/environment/validated_environment.json",
)
_SOURCE_AUTHORITY_SUFFIXES = {".py", ".c", ".json", ".csv"}


def deterministic_source_authority_paths(repo_root: str | Path) -> list[str]:
    """Return the stable source files that determine the registered outputs.

    Generated bytecode, native binaries, caches, result trees, and frozen
    expected outputs are intentionally excluded.
    """
    root = Path(repo_root).resolve()
    paths: set[str] = set()
    for relative_directory in _SOURCE_AUTHORITY_DIRECTORIES:
        directory = root / relative_directory
        if not directory.is_dir():
            continue
        for source in directory.rglob("*"):
            if not source.is_file():
                continue
            if "__pycache__" in source.parts or source.suffix not in _SOURCE_AUTHORITY_SUFFIXES:
                continue
            paths.add(source.relative_to(root).as_posix())
    for relative_path in _SOURCE_AUTHORITY_FILES:
        source = root / relative_path
        if source.is_file():
            paths.add(relative_path)
    return sorted(paths)


def build_protocol_digest(repo_root: str | Path) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    manifest = load_artifact_manifest(root)
    config = load_protocol_config(
        root / "configs/protocol/experiment.json",
        root / "configs/protocol/experiment.schema.json",
    )
    authorities = [
        {"path": relative_path, "sha256": sha256_file(root / relative_path)}
        for relative_path in deterministic_source_authority_paths(root)
    ]
    return {
        "digest_id": "QSA-DETERMINISTIC-PROTOCOL-BINDING-V1",
        "schema_version": 1,
        "protocol_id": config.protocol_id,
        "protocol_sha256": config.sha256,
        "artifact_set_sha256": manifest["artifact_set_sha256"],
        "source_authority_count": len(authorities),
        "source_authorities": authorities,
        "source_authority_set_sha256": hashlib.sha256(
            canonical_json_bytes(authorities)
        ).hexdigest(),
    }


def write_protocol_digest(repo_root: str | Path) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    digest = build_protocol_digest(root)
    target = root / DIGEST_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(
        json.dumps(digest, indent=2, sort_keys=True, allow_nan=False) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    return digest


def load_artifact_manifest(repo_root: str | Path) -> dict[str, Any]:
    path = Path(repo_root).resolve() / MANIFEST_PATH
    value = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(value, dict):
        raise ValueError("deterministic artifact manifest must contain a JSON object")
    return value


def verify_static_artifact_contract(repo_root: str | Path) -> list[str]:
    root = Path(repo_root).resolve()
    errors: list[str] = []
    manifest = load_artifact_manifest(root)
    inventory = json.loads((root / INVENTORY_PATH).read_text(encoding="utf-8"))
    digest = json.loads((root / DIGEST_PATH).read_text(encoding="utf-8"))
    artifacts = manifest.get("artifacts", [])
    if manifest.get("artifact_count") != 37 or len(artifacts) != 37:
        errors.append("deterministic artifact count is not 37")
    if manifest.get("table_count") != 13:
        errors.append("deterministic table count is not 13")
    if manifest.get("representative_object_count") != 24:
        errors.append("representative-object count is not 24")
    paths = [entry.get("path") for entry in artifacts]
    if len(paths) != len(set(paths)):
        errors.append("deterministic artifact paths are not unique")
    if [entry.get("ordinal") for entry in artifacts] != list(range(1, 38)):
        errors.append("deterministic artifact ordinals are not contiguous")
    expected_set = hashlib.sha256(canonical_json_bytes(artifacts)).hexdigest()
    if manifest.get("artifact_set_sha256") != expected_set:
        errors.append("deterministic artifact-set digest is incorrect")
    if inventory.get("artifact_set_sha256") != expected_set:
        errors.append("artifact inventory and hash manifest disagree")
    config = load_protocol_config(root / "configs/protocol/experiment.json", root / "configs/protocol/experiment.schema.json")
    if manifest.get("protocol_sha256") != config.sha256 or digest.get("protocol_sha256") != config.sha256:
        errors.append("deterministic reference is not bound to the active protocol")
    if digest.get("artifact_set_sha256") != expected_set:
        errors.append("protocol digest and artifact hash manifest disagree")
    authorities = digest.get("source_authorities", [])
    recorded_authority_paths = [str(entry.get("path", "")) for entry in authorities]
    expected_authority_paths = deterministic_source_authority_paths(root)
    if recorded_authority_paths != expected_authority_paths:
        errors.append("deterministic source-authority inventory is not current")
    authority_values: list[dict[str, str]] = []
    for entry in authorities:
        source = root / entry.get("path", "")
        if not source.is_file():
            errors.append(f"missing deterministic source authority: {entry.get('path')}")
            continue
        actual = sha256_file(source)
        authority_values.append({"path": entry["path"], "sha256": actual})
        if actual != entry.get("sha256"):
            errors.append(f"deterministic source-authority digest mismatch: {entry['path']}")
    if len(authorities) != int(digest.get("source_authority_count", -1)):
        errors.append("deterministic source-authority count is incorrect")
    actual_authority_set = hashlib.sha256(canonical_json_bytes(authority_values)).hexdigest()
    if authority_values and digest.get("source_authority_set_sha256") != actual_authority_set:
        errors.append("deterministic source-authority-set digest is incorrect")
    for entry in artifacts:
        for field in ("comparison_sha256", "raw_sha256"):
            value = str(entry.get(field, ""))
            if len(value) != 64 or any(char not in "0123456789abcdef" for char in value):
                errors.append(f"invalid {field} for {entry.get('path')}")
    return errors


def verify_execution_tree(repo_root: str | Path, run_root: str | Path) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    run = Path(run_root).resolve()
    manifest = load_artifact_manifest(root)
    checks: list[dict[str, Any]] = []
    for entry in manifest["artifacts"]:
        target = run / entry["path"]
        row: dict[str, Any] = {"ordinal": entry["ordinal"], "path": entry["path"], "artifact_class": entry["artifact_class"]}
        if not target.is_file():
            row.update({"status": "FAIL", "reason": "missing artifact"})
            checks.append(row)
            continue
        raw = sha256_file(target)
        comparison = canonical_csv_sha256(target) if entry["artifact_class"] == "table" else raw
        row.update({
            "raw_sha256": raw,
            "comparison_sha256": comparison,
            "raw_match": raw == entry["raw_sha256"],
            "comparison_match": comparison == entry["comparison_sha256"],
        })
        if entry["artifact_class"] == "table":
            import csv
            with target.open(encoding="utf-8-sig", newline="") as handle:
                reader = csv.reader(handle)
                next(reader, None)
                count = sum(1 for _ in reader)
            row["row_count"] = count
            row["row_count_match"] = count == int(entry["row_count"])
        else:
            parsed = parse_envelope(target.read_bytes())
            row["method_id"] = parsed.header["method_id"]
            row["method_id_match"] = parsed.header["method_id"] == entry["method_id"]
        row["status"] = "PASS" if all(value for key, value in row.items() if key.endswith("_match")) else "FAIL"
        checks.append(row)
    passed = all(row["status"] == "PASS" for row in checks)
    return {"status": "PASS" if passed else "FAIL", "artifact_count": len(checks), "matched_artifact_count": sum(row["status"] == "PASS" for row in checks), "checks": checks}


def compare_execution_trees(repo_root: str | Path, primary: str | Path, independent: str | Path) -> dict[str, Any]:
    root = Path(repo_root).resolve()
    first = Path(primary).resolve()
    second = Path(independent).resolve()
    manifest = load_artifact_manifest(root)
    checks: list[dict[str, Any]] = []
    for entry in manifest["artifacts"]:
        a = first / entry["path"]
        b = second / entry["path"]
        if not a.is_file() or not b.is_file():
            checks.append({"path": entry["path"], "status": "FAIL", "reason": "missing artifact"})
            continue
        digest_a = canonical_csv_sha256(a) if entry["artifact_class"] == "table" else sha256_file(a)
        digest_b = canonical_csv_sha256(b) if entry["artifact_class"] == "table" else sha256_file(b)
        checks.append({"path": entry["path"], "primary_sha256": digest_a, "independent_sha256": digest_b, "status": "PASS" if digest_a == digest_b else "FAIL"})
    passed = all(item["status"] == "PASS" for item in checks)
    return {"status": "PASS" if passed else "FAIL", "comparison_count": len(checks), "matched_count": sum(item["status"] == "PASS" for item in checks), "checks": checks}


def deterministic_reference_summary(repo_root: str | Path) -> dict[str, Any]:
    manifest = load_artifact_manifest(repo_root)
    return {
        "manifest_id": manifest["manifest_id"],
        "artifact_set_sha256": manifest["artifact_set_sha256"],
        "artifact_count": manifest["artifact_count"],
        "table_count": manifest["table_count"],
        "representative_object_count": manifest["representative_object_count"],
    }


def write_artifact_manifest_from_results(repo_root: str | Path, results_root: str | Path) -> dict[str, Any]:
    import csv
    root = Path(repo_root).resolve()
    results = Path(results_root).resolve()
    primary = results / "primary_execution"
    independent = results / "independent_execution"
    old = load_artifact_manifest(root)
    artifacts: list[dict[str, Any]] = []
    for old_entry in old["artifacts"]:
        first = primary / old_entry["path"]
        second = independent / old_entry["path"]
        if not first.is_file() or not second.is_file():
            raise FileNotFoundError(old_entry["path"])
        if old_entry["artifact_class"] == "table":
            first_comparison = canonical_csv_sha256(first)
            second_comparison = canonical_csv_sha256(second)
        else:
            first_comparison = sha256_file(first)
            second_comparison = sha256_file(second)
        if first_comparison != second_comparison:
            raise RuntimeError(f"execution trees disagree for {old_entry['path']}")
        first_raw = sha256_file(first)
        second_raw = sha256_file(second)
        if first_raw != second_raw:
            raise RuntimeError(f"raw execution artifacts disagree for {old_entry['path']}")
        entry = {
            "ordinal": int(old_entry["ordinal"]),
            "artifact_class": old_entry["artifact_class"],
            "path": old_entry["path"],
            "comparison_sha256": first_comparison,
            "raw_sha256": first_raw,
            "file_size_bytes": first.stat().st_size,
            "comparison_rule": old_entry["comparison_rule"],
        }
        if old_entry["artifact_class"] == "table":
            with first.open(encoding="utf-8-sig", newline="") as handle:
                reader = csv.reader(handle)
                columns = next(reader, [])
                row_count = sum(1 for _ in reader)
            entry["row_count"] = row_count
            entry["ordered_columns"] = columns
        else:
            parsed = parse_envelope(first.read_bytes())
            entry["method_id"] = parsed.header["method_id"]
        artifacts.append(entry)
    config = load_protocol_config(root / "configs/protocol/experiment.json", root / "configs/protocol/experiment.schema.json")
    manifest = {
        "manifest_id": "QSA-DETERMINISTIC-ARTIFACT-HASHES-V1",
        "schema_version": 1,
        "protocol_id": config.protocol_id,
        "protocol_sha256": config.sha256,
        "artifact_count": 37,
        "table_count": 13,
        "representative_object_count": 24,
        "artifacts": artifacts,
    }
    manifest["artifact_set_sha256"] = hashlib.sha256(canonical_json_bytes(artifacts)).hexdigest()
    (root / MANIFEST_PATH).write_text(json.dumps(manifest, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8", newline="\n")
    inventory = {
        "inventory_id": "QSA-DETERMINISTIC-ARTIFACT-INVENTORY-V1",
        "schema_version": 1,
        "protocol_id": config.protocol_id,
        "artifact_set_sha256": manifest["artifact_set_sha256"],
        "counts": {"tables": 13, "representative_objects": 24, "total": 37},
        "artifacts": [
            {key: entry[key] for key in ("ordinal", "artifact_class", "path", "row_count", "ordered_columns", "method_id", "file_size_bytes") if key in entry}
            for entry in artifacts
        ],
    }
    (root / INVENTORY_PATH).write_text(json.dumps(inventory, indent=2, sort_keys=True, allow_nan=False) + "\n", encoding="utf-8", newline="\n")
    write_protocol_digest(root)
    return manifest
